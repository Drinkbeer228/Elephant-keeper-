// Подписи (таблички помещений и имена слонов) должны читаться при любом масштабе:
// при отдалении камеры они растут, при сильном приближении — не раздуваются.
// Сцена каждый кадр сообщает, во сколько раз текущий зум отличается от обычного.

let k = 1;

export function setLabelZoom(relative: number): void {
  const r = Math.max(0.05, relative);
  k = r < 0.8 ? Math.min(2.2, 0.8 / r) : r > 1.6 ? 1.6 / r : 1;
}

// Во сколько раз увеличить подпись в мире, чтобы на экране она осталась читаемой
export function labelScale(): number {
  return k;
}
